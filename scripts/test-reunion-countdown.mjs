import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import { validDate, daysUntil, readReunion, reunionUrl, cleanName, reunionLabel } from '../src/lib/reunionCountdown.ts';
const countdownPage = readFileSync(new URL('../src/pages/reunion-countdown.astro', import.meta.url), 'utf8');
assert.match(countdownPage, /Send the countdown to your person/);
assert.match(countdownPage, /Copy partner link/);
assert.match(countdownPage, /countdown_link_copied/);
for (const date of ['2026-02-29','2026-04-31','2026-00-10','2099-13-01','2026-1-01','foo']) assert.equal(validDate(date), false);
assert.ok(validDate('2028-02-29'));
assert.equal(daysUntil('2026-03-09','America/New_York',new Date('2026-03-08T05:00:00Z')),1, 'DST does not shorten a calendar day');
assert.equal(daysUntil('2026-09-15','America/New_York',new Date('2026-09-15T02:00:00Z')),1);
assert.equal(daysUntil('2026-09-15','Asia/Tokyo',new Date('2026-09-15T02:00:00Z')),0);
assert.equal(daysUntil('2026-09-14','UTC',new Date('2026-09-15T02:00:00Z')),-1);
const reunion={you:'Zoë & Alex',partner:'李 🦊',date:'2028-02-29',zone:'Pacific/Auckland'};
const url=new URL(reunionUrl('https://lovefarfox.com',reunion));
assert.deepEqual(readReunion(url.hash),reunion);
assert.equal(url.pathname,'/reunion-countdown/');
assert.equal(url.searchParams.has('you'),false);
assert.equal(url.searchParams.has('date'),false);
assert.equal(url.searchParams.get('utm_campaign'),'reunion_countdown');
for(const hash of ['', '#v=2&date=2028-02-29&zone=UTC','#v=1&date=2026-02-29&zone=UTC','#v=1&date=2026-10-10&zone=wrong', '#'+ 'a'.repeat(2001)]) assert.equal(readReunion(hash),null);
assert.equal([...cleanName('🦊'.repeat(40))].length,32);
assert.equal(cleanName('\nhello\t'),'hello');
assert.match(reunionLabel(0),/Today/);
assert.match(reunionLabel(-1),/remember/);
console.log('Countdown: dates, DST, time zones, unicode, link privacy and malformed links passed.');
const win = { location: { origin: 'https://lovefarfox.com' } };
runInNewContext(readFileSync(new URL('../public/analytics-privacy.js', import.meta.url), 'utf8'), {window:win, URL});
const [name, beforeSend] = win.vaq[0];
assert.equal(name,'beforeSend');
const safe=beforeSend({type:'pageview',url:url.href});
assert.equal(new URL(safe.url).hash,'');
assert.equal(new URL(safe.url).searchParams.get('utm_campaign'),'reunion_countdown');
assert.equal(beforeSend({url:'http://['}),null);
assert.match(readFileSync(new URL('../src/layouts/Layout.astro', import.meta.url),'utf8'), /data-exclude-hash="true"/);
console.log('Both analytics integrations explicitly exclude private URL fragments.');
